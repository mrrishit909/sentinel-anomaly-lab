import { chromium } from "@playwright/test";
import { readFileSync } from "node:fs";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
await page.goto("http://localhost:4361/sentinel-anomaly-lab/");
await page.waitForFunction(() => !!window.__sal);
await page.keyboard.press("Escape");
await page.waitForTimeout(2500);
const id = process.argv[2] ?? "days";
await page.evaluate((i) => window.__sal.jumpTo(i, 0.55), id);
await page.waitForTimeout(800);
await b.startTracing(page, { path: "/tmp/sal/trace.json", categories: ["devtools.timeline", "disabled-by-default-devtools.timeline"] });
await page.evaluate(async (i) => { const sec = document.getElementById(i); const top = sec.getBoundingClientRect().top + scrollY; const h = sec.offsetHeight - innerHeight; for (let k = 0; k <= 40; k++) { scrollTo(0, top + h * (0.55 + (k % 2) * 0.01)); await new Promise((r) => requestAnimationFrame(() => r())); } }, id);
await b.stopTracing();
const ev = JSON.parse(readFileSync("/tmp/sal/trace.json", "utf-8")).traceEvents.filter((e) => e.ph === "X" && e.dur);
const agg = {};
for (const e of ev) agg[e.name] = (agg[e.name] ?? 0) + e.dur / 1000;
console.log(Object.entries(agg).sort((a, b) => b[1] - a[1]).slice(0, 14).map(([k, v]) => `${k} ${v.toFixed(0)}ms`).join("\n"));
await b.close();
